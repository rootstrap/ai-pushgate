import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const validators = [
  {
    functionName: "validatePushgateConfig",
    outputPath: "src/generated/pushgate-config-v2-validator.ts",
    schemaPath: "schemas/pushgate-config-v2.schema.json",
  },
  {
    functionName: "validateAiReviewOutput",
    outputPath: "src/generated/ai-review-output-v1-validator.ts",
    schemaPath: "schemas/ai-review-output-v1.schema.json",
  },
];

for (const validator of validators) {
  const source = await buildValidatorModule(validator);

  await mkdir(dirname(validator.outputPath), { recursive: true });
  await writeFile(validator.outputPath, source);

  console.log(
    `Generated ${validator.outputPath} from ${validator.schemaPath}`,
  );
}

async function buildValidatorModule({ functionName, schemaPath }) {
  const schema = JSON.parse(await readFile(schemaPath, "utf8"));
  const ajv = new Ajv({
    allErrors: true,
    code: {
      esm: true,
      lines: true,
      source: true,
    },
    strict: true,
  });
  const validate = ajv.compile(schema);
  const { code, validatorName } = normalizeStandaloneCode(
    standaloneCode(ajv, validate),
  );

  return [
    "// @ts-nocheck",
    "/*",
    " * Generated by scripts/build-validators.mjs.",
    ` * Source schema: ${schemaPath}.`,
    " * Do not edit this file directly.",
    " */",
    "",
    "export interface SchemaValidationError {",
    "  readonly instancePath: string;",
    "  readonly schemaPath: string;",
    "  readonly keyword: string;",
    "  readonly params: Readonly<Record<string, unknown>>;",
    "  readonly message?: string;",
    "}",
    "",
    "export interface SchemaValidationResult {",
    "  readonly valid: boolean;",
    "  readonly errors?: readonly SchemaValidationError[];",
    "}",
    "",
    "function ucs2length(str) {",
    "  const len = str.length;",
    "  let length = 0;",
    "  let pos = 0;",
    "  let value;",
    "",
    "  while (pos < len) {",
    "    length++;",
    "    value = str.charCodeAt(pos++);",
    "",
    "    if (value >= 0xd800 && value <= 0xdbff && pos < len) {",
    "      value = str.charCodeAt(pos);",
    "",
    "      if ((value & 0xfc00) === 0xdc00) {",
    "        pos++;",
    "      }",
    "    }",
    "  }",
    "",
    "  return length;",
    "}",
    "",
    code,
    "",
    `const validateSchema = ${validatorName};`,
    "",
    "function normalizeErrors(errors) {",
    "  return (errors ?? []).map((error) => ({",
    '    instancePath: error.instancePath ?? "",',
    '    schemaPath: error.schemaPath ?? "",',
    '    keyword: error.keyword ?? "",',
    "    params: { ...(error.params ?? {}) },",
    '    ...(typeof error.message === "string"',
    "      ? { message: error.message }",
    "      : {}),",
    "  }));",
    "}",
    "",
    `export function ${functionName}(value: unknown): SchemaValidationResult {`,
    "  const valid = validateSchema(value);",
    "",
    "  if (valid) {",
    "    return { valid: true };",
    "  }",
    "",
    "  return {",
    "    valid: false,",
    "    errors: normalizeErrors(validateSchema.errors),",
    "  };",
    "}",
    "",
  ].join("\n");
}

function normalizeStandaloneCode(rawCode) {
  const validatorMatch = rawCode.match(/export const validate = (validate\d+);/);

  if (!validatorMatch) {
    throw new Error("Could not find Ajv standalone validator export.");
  }

  const validatorName = validatorMatch[1];
  const code = rawCode
    .replace(/^"use strict";\n/, "")
    .replace(/export const validate = validate\d+;\n/, "")
    .replace(/export default validate\d+;\n/, "")
    .replace(
      /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
      "const $1 = ucs2length;",
    )
    .trim();

  if (code.includes("require(")) {
    throw new Error("Generated validator still contains a runtime require().");
  }

  return {
    code,
    validatorName,
  };
}
